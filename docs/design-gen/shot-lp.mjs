import { chromium } from 'playwright';
import { pathToFileURL } from 'node:url';
const b = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await b.newContext({ viewport: { width: 1280, height: 900 }, deviceScaleFactor: 1.5 });
const p = await ctx.newPage();
const url = pathToFileURL('C:/dev/BudgetBook/kakeibo-saas/lp/index.html').href;
await p.goto(url, { waitUntil: 'networkidle' });
await p.waitForTimeout(1200);
await p.screenshot({ path: 'shots/redesign-applied/lp-full.png', fullPage: true });
await p.screenshot({ path: 'shots/redesign-applied/lp-top.png' });
await ctx.close(); await b.close();
console.log('done lp');
