// iOSアプリの公開状態。アプリ内の告知はすべてここを見る。
//
// live が false のあいだは「◯月◯日に公開します」の案内、true にすると「公開しました」の
// 案内に切り替わる。告知を2種類そのまま置いておくのではなく、ここ1か所で切り替える。
//
// ⚠ live を true にしてよいのは、公開を確認したあとだけ。目視で判断しない。
//    node scripts/check-ios-live.mjs が通ってから変える。
//    App Store のページは公開するまで存在せず、未公開IDは 404 を返す
//    （実測 2026-09-09 審査待ち時点: iTunes Lookup が resultCount=0）。
//
// ⚠ date は実際に公開した日。これが更新情報の id になり、既読管理
//    （localStorage の kk_update_seen）のキーになる。あとから書き換えると、
//    既に読んだ人全員に未読の赤ドットが戻る。
export const IOS_APP = {
  live: false,
  date: '', // 公開した日。例: '2026-09-25'
  // App Store が正規とするアプリ名入りのURLを使う。
  // ⚠ 予約注文を公開した直後（2026-09-14 19:51）は、短い /jp/app/id6806592989 が 404 で、
  //    アプリ名入りの形だけ 200 だった。5分後には短い形も 200 になった。反映の途中で
  //    片方だけ開けない時間がある。/us/ は 404（日本のみ配信のため）。
  //    App Store Connect の「App Storeで表示」は /us/ を指すので、そのままコピーしないこと。
  url: 'https://apps.apple.com/jp/app/kurofukubo-%E8%A4%87%E5%BC%8F%E7%B0%BF%E8%A8%98%E3%81%AE%E5%AE%B6%E8%A8%88%E7%B0%BF/id6806592989',

  // App Store で公開する予定日。App Store Connect の「予約注文」のリリース日（日本 2026-09-25）。
  // ⚠ バージョン側のリリース方式は予約注文の設定で「手動」に変わっている。以前入れていた
  //    「GMT 9/24 21:00 に自動リリース」はもう効いておらず、公開日はこの予約注文の日付で決まる。
  // 公開日が動いたらここだけ直す。更新情報の id にも入るので、変えると未読に戻る。
  // ⚠ 予約した人には、日付が変わってもAppleから通知されない。変えたらこちらから知らせること。
  releaseOn: '2026-09-25',

  // App Store で予約注文を受け付けているか。true のあいだは公開前でも予約ページへのリンクを出す。
  // ⚠ 予約注文用のページは「このバージョンをリリース」を押すまで存在しない（それまでは 404）。
  //    ページが開けることを確かめてから true にする。
  preorder: true,
};

// 「9月25日」のような表示用の文字列。
const [, m, d] = IOS_APP.releaseOn.split('-');
export const IOS_RELEASE_LABEL = `${Number(m)}月${Number(d)}日`;
